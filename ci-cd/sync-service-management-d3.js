const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { isEntryPoint } = require('./lib/entry-point.js');

/**
 * sync-service-management-d3 — vendor D3 ESM into the Service Management SPA.
 * No CDN. Import map points at apps/service-management/vendor/d3/index.js.
 */

const D3_PACKAGE = path.join('node_modules', 'd3', 'src', 'index.js');
const D3_PACKAGE_ALT = path.join('apps', 'service-management', 'node_modules', 'd3', 'src', 'index.js');
const VENDORED_FILE = path.join('apps', 'service-management', 'vendor', 'd3', 'index.js');

const VENDORED_HEADER = '/* Vendored D3 ESM bundle. Generated by'
  + ' ci-cd/sync-service-management-d3.js — do not edit. */\n';

function resolveD3Entry(root, exists) {
  const primary = path.join(root, D3_PACKAGE);
  if (exists(primary)) return primary;
  const alt = path.join(root, D3_PACKAGE_ALT);
  if (exists(alt)) return alt;
  // bun may hoist under .bun — resolve via require
  try {
    return require.resolve('d3/src/index.js', { paths: [root, path.join(root, 'apps/service-management')] });
  } catch (_error) {
    try {
      return require.resolve('d3', { paths: [root, path.join(root, 'apps/service-management')] });
    } catch (_error2) {
      return null;
    }
  }
}

function syncServiceManagementD3(options = {}) {
  const root = options.root || process.cwd();
  const spawn = options.spawn || spawnSync;
  const exists = options.exists || fs.existsSync;
  const readFile = options.readFile || fs.readFileSync;
  const writeFile = options.writeFile || ((target, contents) => {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, contents);
  });
  const logger = options.logger || console;

  const sourceEntry = options.sourceEntry || resolveD3Entry(root, exists);
  if (!sourceEntry || !exists(sourceEntry)) {
    logger.error(`[ci] d3 sync: d3 package entry not found under ${root}`);
    return 1;
  }

  const bunExecutable = path.basename(process.execPath).startsWith('bun') ? process.execPath : 'bun';
  const distFile = path.join(root, 'apps', 'service-management', 'vendor', 'd3', '.build.mjs');
  const build = spawn(bunExecutable, [
    'build', sourceEntry,
    '--outfile', distFile,
    '--format', 'esm',
    '--target', 'browser'
  ], { cwd: root, stdio: 'inherit' });
  if (build.status !== 0) {
    logger.error(`[ci] d3 sync: bun build failed with status ${String(build.status)}.`);
    return build.status || 1;
  }
  if (!exists(distFile)) {
    logger.error(`[ci] d3 sync: build reported success but ${distFile} is missing.`);
    return 1;
  }

  const artifact = readFile(distFile, 'utf-8');
  if (!artifact.includes('scaleLinear') && !artifact.includes('scale')) {
    logger.error('[ci] d3 sync: bundled artifact missing expected d3 scale exports.');
    return 1;
  }

  const vendored = path.join(root, VENDORED_FILE);
  writeFile(vendored, `${VENDORED_HEADER}${artifact}`);
  try { fs.unlinkSync(distFile); } catch (_error) { /* ignore */ }
  logger.log(`[ci] d3 synced: ${VENDORED_FILE}`);
  return 0;
}

if (isEntryPoint(module)) {
  process.exitCode = syncServiceManagementD3();
}

module.exports = {
  syncServiceManagementD3,
  VENDORED_FILE
};
